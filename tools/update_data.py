#!/usr/bin/env python3
"""Rebuild data/set19.js from the Set 19 data MetaTFT ships in its site bundle.

Usage:
    python3 tools/update_data.py                 # download the live bundle
    python3 tools/update_data.py path/to/main.js # use a bundle you already saved

MetaTFT embeds the new-set preview data (units, traits) as JSON.parse(`...`)
literals in its main bundle. This finds those literals by shape, cleans the
tooltip markup, and writes a compact file the site loads.
"""
import json
import re
import sys
import urllib.request

SET = "19"
SITE = "https://www.metatft.com"
UA = {"User-Agent": "Mozilla/5.0 (study-tool data refresh)"}
CDN = "https://cdn.metatft.com"


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return r.read().decode("utf-8")


def load_bundle(argv):
    if len(argv) > 1:
        return open(argv[1], encoding="utf-8").read()
    html = fetch(SITE + "/new-set")
    m = re.search(r'src="(/assets/main-[^"]+\.js)"', html)
    if not m:
        sys.exit("Could not find the main bundle on metatft.com/new-set")
    return fetch(SITE + m.group(1))


def json_literals(js):
    """Yield every JSON.parse(`[{"apiName":"DA_<set>_...`) array in the bundle."""
    marker = 'JSON.parse(`[{"apiName":"DA_' + SET + "_"
    start = 0
    while True:
        i = js.find(marker, start)
        if i < 0:
            return
        s = i + len("JSON.parse(`")
        e = js.find("`)", s)
        raw = js[s:e].replace("\\`", "`").replace("\\\\", "\\")
        yield json.loads(raw)
        start = e


def clean(raw):
    t = raw or ""
    t = re.sub(r"<TFTCurveTable[^>]*\|>", "X", t)
    t = re.sub(r"<img[^>]*\|>\s*", "", t)
    t = re.sub(r"\{[A-Za-z0-9_.]+\}", "", t)
    t = re.sub(r"<[^>]+>", "", t)
    t = re.sub(r"\s+", " ", t).strip()
    return t


def icon_key(api):
    return re.sub(r"[^\w]", "", re.sub(r"_\d+$", "", api)).lower()


def main():
    js = load_bundle(sys.argv)
    units = traits = None
    for arr in json_literals(js):
        if "unlockable" in arr[0]:
            units = arr
        elif "effects" in arr[0]:
            traits = arr
    if not units or not traits:
        sys.exit("Set %s units/traits not found in bundle" % SET)

    meta = {"set": SET, "name": "", "generated": ""}
    m = re.search(r'set:"TFTSet' + SET + r'",name:"([^"]+)"[^}]*?generated:"([^"]+)"', js)
    if m:
        meta["name"], meta["generated"] = m.group(1), m.group(2)

    out_units = []
    for u in units:
        ab = u.get("ability") or {}
        desc = ab.get("description_dedeved") or ab.get("description") or ""
        unlock = None
        if u.get("unlockable"):
            # Multi-part conditions (Baron, Rakan) arrive comma-joined: "...ensemble., Deal ..."
            text = clean(u.get("unlockConditionRaw"))
            unlock = [p.strip().rstrip(".") + "." for p in re.split(r"(?<=[.+]), (?=[A-Z])", text)]
        out_units.append({
            "id": u["apiName"],
            "name": u["name"],
            "cost": u["cost"],
            "role": u.get("role") or "",
            "traits": [t["name"] for t in u.get("traits", [])],
            "ability": {"name": ab.get("name") or "", "desc": desc.strip()},
            "unlock": unlock,
            "img": CDN + "/cdn-cgi/image/width=480,format=auto/" + CDN
            + "/file/metatft/championsplashes/" + u["apiName"].lower() + ".png",
        })

    out_traits = []
    for t in traits:
        desc = t.get("description_dedeved") or t.get("description") or ""
        out_traits.append({
            "id": t["apiName"],
            "name": t["name"],
            "type": t.get("type") or "",
            "desc": desc.strip(),
            "breakpoints": [e["minUnits"] for e in t.get("effects", [])],
            "units": [x["unit"] for x in t.get("units", [])],
            "icon": CDN + "/file/metatft/traits/" + icon_key(t["apiName"]) + ".png",
        })

    data = {"meta": meta, "units": out_units, "traits": out_traits}
    with open("data/set%s.js" % SET, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/update_data.py from metatft.com. Do not edit by hand.\n")
        f.write("window.SET_DATA = ")
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print("units %d (unlockable %d), traits %d" % (
        len(out_units), sum(1 for u in out_units if u["unlock"]), len(out_traits)))


if __name__ == "__main__":
    main()
